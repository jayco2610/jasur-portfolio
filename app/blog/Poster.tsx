"use client";

/* Обложка-постер статьи: нарисованная картинка, которая показывается целиком,
   а не режется в полосу 16:10.

   Отдельный клиентский компонент, а не <img> прямо в странице, из-за
   предупреждения в консоли. <img> в серверном компоненте React записывает
   в данные страницы подсказкой «заранее загрузить картинку». Шапка статьи
   ссылается на перевод, Next заранее подтягивает данные перевода, и браузер
   грузил обложку статьи-пары, которая на этой странице не нужна: «preloaded
   but not used» на обеих статьях с постером. Из клиентского компонента
   подсказка в эти данные не попадает, а в html самой страницы остаётся. */
export default function Poster({ src }: { src: string }) {
  return (
    <div className="nm-art-poster">
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={src} alt="" fetchPriority="high" />
    </div>
  );
}
