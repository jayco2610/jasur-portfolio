"use client";

import { useEffect, type ReactNode } from "react";
import { useLanguage } from "@/context/LanguageContext";

/* Язык макета. Отдельного состояния здесь нет: язык один на весь сайт и живёт
   в context/LanguageContext.tsx, на нём же работают старые страницы, демо и
   статьи. Выбор хранится в памяти браузера (localStorage "lang"), поэтому он
   переживает и переход по ссылке внутри макета, и уход на старые страницы,
   и обновление страницы.

   Как устроено. Страница макета серверная: тексты и списки статей она
   собирает при сборке, файлы читает на сервере. Она собирает тело дважды,
   русское и английское, и отдаёт оба в ByLang. ByLang ничего не считает,
   только выбирает, какое из двух показать.

   Почему без ошибки гидратации. Сервер не знает, что выбрал человек, и
   всегда рисует русский. Контекст в браузере тоже стартует с русского и
   читает сохранённый язык только после гидратации, в эффекте. Первая
   отрисовка в браузере поэтому совпадает с серверной буква в букву, а
   английский подставляется следующим кадром. Так же ведёт себя старый сайт:
   мигание ровно то же, не дольше.

   Даты, числа и списки статей для обоих языков считаются на сервере и
   приходят готовыми строками. Посчитай их браузер, дата зависела бы от его
   часового пояса и расходилась бы с серверной. */
export function ByLang({ ru, en }: { ru: ReactNode; en: ReactNode }) {
  const { lang } = useLanguage();
  return <>{lang === "en" ? en : ru}</>;
}

/* Атрибут lang у <html>. Корневой layout сайта ставит "ru" навсегда, и читалка
   экрана читала бы английский текст русским голосом, а браузер переносил бы
   его по русским правилам. Пока открыт макет, атрибут идёт за выбранным
   языком; при уходе из макета возвращается к тому, что стоит в layout. */
export function LangAttr() {
  const { lang, toggle } = useLanguage();
  useEffect(() => {
    const html = document.documentElement;
    html.lang = lang;
    return () => {
      html.lang = "ru";
    };
  }, [lang]);

  /* Кнопка «назад» в браузере может достать страницу из кэша целиком, вместе
     с языком, который был на ней до ухода. Если на другой странице язык с тех
     пор переключили, такая страница показалась бы на старом. При возврате из
     кэша сверяем язык с сохранённым и, если разошлись, переключаем. */
  useEffect(() => {
    const sync = (e: PageTransitionEvent) => {
      if (!e.persisted) return;
      let saved: string | null = null;
      try {
        saved = localStorage.getItem("lang");
      } catch {
        return;
      }
      if ((saved === "ru" || saved === "en") && saved !== lang) toggle();
    };
    window.addEventListener("pageshow", sync);
    return () => window.removeEventListener("pageshow", sync);
  }, [lang, toggle]);

  return null;
}
