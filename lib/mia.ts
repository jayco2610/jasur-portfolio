/** Строка фрагмента, начинающаяся с заданных слов, без маркера списка. */
export function miaLine(chunkId: string, startsWith: string): string {
  const chunk = MIA_CHUNKS.find((c) => c.id === chunkId);
  const line = chunk?.text
    .split("\n")
    .map((l) => l.replace(/^- /, ""))
    .find((l) => l.startsWith(startsWith));
  if (!line) throw new Error(`Mia: нет строки «${startsWith}» во фрагменте ${chunkId}`);
  return line;
}

